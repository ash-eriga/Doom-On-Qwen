#!/usr/bin/env python3
"""Turn the key schedule into the guest's baked-in table.

Reads the "frame mask" schedule and writes port-lf/qwen_schedule.inc: one entry per mask
change, {0, 0} terminates — so a frame-0 entry is dropped (the key state starts at 0 and
the runner's frame-0 poke was a no-op anyway).

    python gen_schedule.py <oracle/sched.txt> <port-lf/qwen_schedule.inc>
"""
import sys


def main() -> int:
    src, dst = sys.argv[1], sys.argv[2]
    entries, last = [], None
    for line in open(src):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        fr, msk = int(line.split()[0]), int(line.split()[1])
        if fr == 0:
            continue  # {0,0} is the terminator; the frame-0 mask is the initial state
        if msk != last:
            entries.append((fr, msk))
            last = msk
    out = ["/* Generated by free/gen_schedule.py from the key schedule: the autopilot",
           " * playthrough, baked into the guest. One entry per mask change; {0, 0} terminates. */"]
    out += [f"    {{ {fr}, 0x{msk:x} }}," for fr, msk in entries]
    out += ["    { 0, 0 },", ""]
    open(dst, "w").write("\n".join(out))
    print(f"{len(entries)} mask-change events -> {dst}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
